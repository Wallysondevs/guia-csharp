using System.Collections.Immutable;
using System.Globalization;
using System.Runtime.InteropServices.JavaScript;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Emit;
using Microsoft.CodeAnalysis.Text;

namespace Motor;

/// O compilador: Roslyn com as MESMAS opções do `dotnet run arquivo.cs` do .NET 10 (SDK 10.0.112):
/// C# 14, Nullable enable, ImplicitUsings (os mesmos global using), /warn:10, Debug, /nowarn:1701,1702,IL2121,
/// /define:TRACE;DEBUG;NET;NET10_0;…, /features:FileBasedProgram. Mensagens em pt-BR (satélites do Roslyn).
public static partial class Compilador
{
    static MetadataReference[]? referencias;
    static byte[] dll = [], pdb = [];
    static readonly CultureInfo PtBr = new("pt-BR");

    const string GlobalUsings = """
        // <auto-generated/>
        global using System;
        global using System.Collections.Generic;
        global using System.IO;
        global using System.Linq;
        global using System.Net.Http;
        global using System.Threading;
        global using System.Threading.Tasks;

        """;

    static readonly string[] Simbolos = "TRACE;DEBUG;NET;NET10_0;NETCOREAPP;NET5_0_OR_GREATER;NET6_0_OR_GREATER;NET7_0_OR_GREATER;NET8_0_OR_GREATER;NET9_0_OR_GREATER;NET10_0_OR_GREATER;NETCOREAPP1_0_OR_GREATER;NETCOREAPP1_1_OR_GREATER;NETCOREAPP2_0_OR_GREATER;NETCOREAPP2_1_OR_GREATER;NETCOREAPP2_2_OR_GREATER;NETCOREAPP3_0_OR_GREATER;NETCOREAPP3_1_OR_GREATER".Split(';');

    /// pacote: [u32 n] n × ([u16 tamNome][nome UTF-8][u32 tam][bytes])  (os reference assemblies do Microsoft.NETCore.App.Ref 10)
    [JSExport]
    public static int CarregarReferencias(byte[] pacote)
    {
        var lista = new List<MetadataReference>();
        int p = 0;
        uint n = BitConverter.ToUInt32(pacote, p); p += 4;
        for (int i = 0; i < n; i++)
        {
            int tn = BitConverter.ToUInt16(pacote, p); p += 2;
            string nome = Encoding.UTF8.GetString(pacote, p, tn); p += tn;
            int t = (int)BitConverter.ToUInt32(pacote, p); p += 4;
            var img = ImmutableArray.Create(pacote, p, t); p += t;
            lista.Add(MetadataReference.CreateFromImage(img, filePath: "/usr/lib/dotnet/packs/Microsoft.NETCore.App.Ref/10.0.12/ref/net10.0/" + nome));
        }
        referencias = lista.ToArray();
        // mensagens do compilador em português: os satélites pt-BR do Roslyn do laboratório (embutidos no Motor.dll)
        var satelites = new Dictionary<string, System.Reflection.Assembly>();
        foreach (var r in typeof(Compilador).Assembly.GetManifestResourceNames().Where(r => r.StartsWith("sat/")))
        {
            using var st = typeof(Compilador).Assembly.GetManifestResourceStream(r)!;
            var a = System.Runtime.Loader.AssemblyLoadContext.Default.LoadFromStream(st);
            satelites[a.GetName().Name!] = a;
        }
        System.Runtime.Loader.AssemblyLoadContext.Default.Resolving += (_, n) => n.CultureName == "pt-BR" ? satelites.GetValueOrDefault(n.Name ?? "") : null;
        CultureInfo.DefaultThreadCurrentUICulture = PtBr;
        CultureInfo.CurrentUICulture = PtBr;
        return referencias.Length;
    }

    /// pedido (JSON): { "arquivos": [{"nome","codigo"}], "pasta": "/home/ana/cs", "projeto": "Exemplo" ou null, "nome": "ola" }
    /// resposta (JSON): { "ok", "texto" (como o dotnet mostra), "diags": [{"sev","id","linha","msg"}], "ms" }
    [JSExport]
    public static string Compilar(string pedido)
    {
        var t0 = DateTime.UtcNow;
        using var doc = JsonDocument.Parse(pedido);
        var raiz = doc.RootElement;
        string pasta = raiz.GetProperty("pasta").GetString()!.TrimEnd('/');
        string? projeto = raiz.TryGetProperty("projeto", out var pj) && pj.ValueKind == JsonValueKind.String ? pj.GetString() : null;
        string nome = raiz.GetProperty("nome").GetString()!;
        CultureInfo.CurrentUICulture = PtBr;
        CultureInfo.CurrentCulture = PtBr;

        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, DocumentationMode.None, SourceCodeKind.Regular, Simbolos);
        if (projeto == null)
            parse = parse.WithFeatures([new("FileBasedProgram", "true"), new("InterceptorsNamespaces", ";Microsoft.AspNetCore.Http.Generated;Microsoft.Extensions.Configuration.Binder.SourceGeneration;Microsoft.Extensions.Validation.Generated")]);
        else
            parse = parse.WithFeatures([new("InterceptorsNamespaces", ";Microsoft.AspNetCore.Http.Generated;Microsoft.Extensions.Configuration.Binder.SourceGeneration;Microsoft.Extensions.Validation.Generated")]);

        var arvores = new List<SyntaxTree>();
        foreach (var a in raiz.GetProperty("arquivos").EnumerateArray())
        {
            string an = a.GetProperty("nome").GetString()!;
            if (!an.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) continue;
            string codigo = a.GetProperty("codigo").GetString() ?? "";
            arvores.Add(CSharpSyntaxTree.ParseText(SourceText.From(codigo, Encoding.UTF8, SourceHashAlgorithm.Sha256), parse, pasta + "/" + an));
        }
        string obj = projeto == null ? "/home/ana/.local/share/dotnet/runfile/" + nome + "/obj/debug/" : pasta + "/obj/Debug/net10.0/";
        arvores.Add(CSharpSyntaxTree.ParseText(SourceText.From(GlobalUsings, Encoding.UTF8, SourceHashAlgorithm.Sha256), parse, obj + nome + ".GlobalUsings.g.cs"));
        arvores.Add(CSharpSyntaxTree.ParseText(SourceText.From(
            "// <autogenerated />\nusing System;\nusing System.Reflection;\n[assembly: global::System.Runtime.Versioning.TargetFrameworkAttribute(\".NETCoreApp,Version=v10.0\", FrameworkDisplayName = \".NET 10.0\")]\n", Encoding.UTF8, SourceHashAlgorithm.Sha256), parse, obj + ".NETCoreApp,Version=v10.0.AssemblyAttributes.cs"));
        string q = nome.Replace("\\", "\\\\").Replace("\"", "\\\"");
        arvores.Add(CSharpSyntaxTree.ParseText(SourceText.From(
            "using System;\nusing System.Reflection;\n" +
            $"[assembly: System.Reflection.AssemblyCompanyAttribute(\"{q}\")]\n[assembly: System.Reflection.AssemblyConfigurationAttribute(\"Debug\")]\n[assembly: System.Reflection.AssemblyFileVersionAttribute(\"1.0.0.0\")]\n[assembly: System.Reflection.AssemblyInformationalVersionAttribute(\"1.0.0\")]\n[assembly: System.Reflection.AssemblyProductAttribute(\"{q}\")]\n[assembly: System.Reflection.AssemblyTitleAttribute(\"{q}\")]\n[assembly: System.Reflection.AssemblyVersionAttribute(\"1.0.0.0\")]\n",
            Encoding.UTF8, SourceHashAlgorithm.Sha256), parse, obj + nome + ".AssemblyInfo.cs"));

        var opcoes = new CSharpCompilationOptions(OutputKind.ConsoleApplication,
                nullableContextOptions: NullableContextOptions.Enable,
                optimizationLevel: OptimizationLevel.Debug,
                checkOverflow: false, allowUnsafe: false, warningLevel: 10, deterministic: true, concurrentBuild: false,
                specificDiagnosticOptions: new Dictionary<string, ReportDiagnostic> {
                    ["CS1701"] = ReportDiagnostic.Suppress, ["CS1702"] = ReportDiagnostic.Suppress, ["IL2121"] = ReportDiagnostic.Suppress,
                    ["SYSLIB0011"] = ReportDiagnostic.Error,
                })
            .WithPlatform(Platform.AnyCpu);

        var comp = CSharpCompilation.Create(nome, arvores, referencias ?? throw new InvalidOperationException("referências não carregadas"), opcoes);
        using var msDll = new MemoryStream();
        using var msPdb = new MemoryStream();
        // Como o csc: primeiro os erros de sintaxe; se houver, para aí (não mostra os semânticos).
        // Depois as declarações; se houver erro, para. Só então compila os métodos e gera o .dll.
        static bool Visivel(Diagnostic d) => !d.IsSuppressed && (d.Severity == DiagnosticSeverity.Error || d.Severity == DiagnosticSeverity.Warning);
        var opDiag = opcoes.SpecificDiagnosticOptions;
        Diagnostic? Filtrar(Diagnostic d)
        {
            return opDiag.TryGetValue(d.Id, out var rd) && rd == ReportDiagnostic.Suppress ? null : d;
        }
        List<Diagnostic> Etapa(IEnumerable<Diagnostic> ds) => ds.Select(Filtrar).Where(d => d != null && Visivel(d)).Select(d => d!).ToList();
        var visiveis = Etapa(comp.GetParseDiagnostics());
        bool ok = false;
        if (!visiveis.Any(d => d.Severity == DiagnosticSeverity.Error))
        {
            visiveis.AddRange(Etapa(comp.GetDeclarationDiagnostics()));
            if (!visiveis.Any(d => d.Severity == DiagnosticSeverity.Error))
            {
                var res = comp.Emit(msDll, msPdb, options: new EmitOptions(debugInformationFormat: DebugInformationFormat.PortablePdb, pdbFilePath: obj + nome + ".pdb"));
                visiveis = res.Diagnostics.Where(Visivel).ToList();
                ok = res.Success;
            }
        }
        // o dotnet mostra primeiro os erros, depois os avisos (cada grupo na ordem do código)
        var ordenados = visiveis.Where(d => d.Severity == DiagnosticSeverity.Error).Concat(visiveis.Where(d => d.Severity == DiagnosticSeverity.Warning)).ToList();
        string sufixo = projeto == null ? "" : " [" + pasta + "/" + projeto + ".csproj]";
        var texto = new StringBuilder();
        var vistos = new HashSet<string>();
        using var buf = new MemoryStream();
        using var w = new Utf8JsonWriter(buf);
        w.WriteStartObject();
        w.WriteBoolean("ok", ok);
        w.WriteStartArray("diags");
        foreach (var d in ordenados)
        {
            string linha = CSharpDiagnosticFormatter.Instance.Format(d, PtBr) + sufixo;
            if (!vistos.Add(linha)) continue;
            texto.Append(linha).Append('\n');
            w.WriteStartObject();
            w.WriteString("sev", d.Severity == DiagnosticSeverity.Error ? "error" : "warning");
            w.WriteString("id", d.Id);
            w.WriteString("linha", linha);
            w.WriteString("msg", d.GetMessage(PtBr));
            var pos = d.Location.GetLineSpan();
            w.WriteString("arquivo", pos.Path ?? "");
            w.WriteNumber("l", pos.StartLinePosition.Line + 1);
            w.WriteNumber("c", pos.StartLinePosition.Character + 1);
            w.WriteEndObject();
        }
        w.WriteEndArray();
        if (!ok) texto.Append("\nOcorreu uma falha no build. Corrija os erros de build e execute novamente.\n");
        w.WriteString("texto", texto.ToString());
        w.WriteNumber("ms", (int)(DateTime.UtcNow - t0).TotalMilliseconds);
        w.WriteEndObject();
        w.Flush();
        dll = ok ? msDll.ToArray() : [];
        pdb = ok ? msPdb.ToArray() : [];
        return Encoding.UTF8.GetString(buf.ToArray());
    }

    [JSExport]
    public static string Diagnostico()
    {
        var sb = new StringBuilder();
        sb.Append(CultureInfo.CurrentUICulture.Name).Append('\n');
        try { var a = typeof(CSharpCompilation).Assembly.GetSatelliteAssembly(PtBr); sb.Append(a.FullName); } catch (Exception e) { sb.Append(e.GetType().Name + ": " + e.Message); }
        foreach (var a in AppDomain.CurrentDomain.GetAssemblies()) if (a.FullName!.Contains("resources") || a.FullName.Contains("CodeAnalysis")) sb.Append('\n').Append(a.FullName);
        return sb.ToString();
    }

    [JSExport] public static byte[] Dll() => dll;
    [JSExport] public static byte[] Pdb() => pdb;
}
